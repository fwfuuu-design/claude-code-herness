export function localizeVisualizationStep(
  locale: string,
  version: string | undefined,
  index: number,
  fallback: LocalizedStep
): LocalizedStep {
  if (locale !== "zh" || !version) return fallback;
  return ZH_STEPS[version]?.[index] ?? fallback;
}

export function localizeVisualizationLabel(locale: string, text: string): string {
  if (locale !== "zh") return text;
  return ZH_LABELS[text] ?? text;
}
